-- Q18. Create a reusable view that pre-joins the fact table with
--      all three dimensions, so future analysts can query plain
--      column names without repeating the JOINs every time.
DROP VIEW IF EXISTS vw_orders_full;
CREATE VIEW vw_orders_full AS
SELECT
    f.order_id,
    f.order_date,
    f.product_id,
    c.category_name,
    f.price,
    f.discount_percent,
    f.discounted_price,
    f.quantity_sold,
    r.region_name,
    p.payment_method,
    f.rating,
    f.review_count,
    f.total_revenue
FROM fact_orders f
JOIN dim_category c ON f.category_id = c.category_id
JOIN dim_region   r ON f.region_id   = r.region_id
JOIN dim_payment  p ON f.payment_id  = p.payment_id;

-- Example usage of the view: top 5 highest revenue orders in Asia
SELECT order_id, order_date, category_name, region_name, total_revenue
FROM vw_orders_full
WHERE region_name = 'Asia'
ORDER BY total_revenue DESC
LIMIT 5;

