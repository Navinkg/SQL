/* ----------------------------------------------------------
   SECTION 1: JOINS
   ---------------------------------------------------------- */

-- Q1. List the first 10 orders with their category, region and
--     payment method names instead of raw IDs (INNER JOIN across
--     3 dimension tables).
SELECT
    f.order_id,
    f.order_date,
    c.category_name,
    r.region_name,
    p.payment_method,
    f.total_revenue
FROM fact_orders f
JOIN dim_category c ON f.category_id = c.category_id
JOIN dim_region   r ON f.region_id   = r.region_id
JOIN dim_payment  p ON f.payment_id  = p.payment_id
ORDER BY f.order_id
LIMIT 10;

-- Q2. Total revenue generated by each product category, sorted
--     from highest to lowest (JOIN + GROUP BY).
SELECT
    c.category_name,
    ROUND(SUM(f.total_revenue), 2) AS total_revenue,
    COUNT(*) AS number_of_orders
FROM fact_orders f
JOIN dim_category c ON f.category_id = c.category_id
GROUP BY c.category_name
ORDER BY total_revenue DESC;

-- Q3. Which payment method is most popular in each region?
--     (JOIN + GROUP BY on two dimensions together)
SELECT
    r.region_name,
    p.payment_method,
    COUNT(*) AS order_count
FROM fact_orders f
JOIN dim_region  r ON f.region_id  = r.region_id
JOIN dim_payment p ON f.payment_id = p.payment_id
GROUP BY r.region_name, p.payment_method
ORDER BY r.region_name, order_count DESC;


/* ----------------------------------------------------------
   SECTION 2: GROUP BY / HAVING / AGGREGATE FUNCTIONS
   ---------------------------------------------------------- */

-- Q4. Find categories where average customer rating is below 3.5
--     (aggregate + HAVING, a filter that runs AFTER grouping).
SELECT
    c.category_name,
    ROUND(AVG(f.rating), 2) AS avg_rating,
    COUNT(*) AS total_orders
FROM fact_orders f
JOIN dim_category c ON f.category_id = c.category_id
GROUP BY c.category_name
HAVING AVG(f.rating) < 3.5
ORDER BY avg_rating;

-- Q5. Monthly order volume and revenue trend for 2023
--     (date functions + GROUP BY on a derived column).
SELECT
    strftime('%Y-%m', order_date) AS order_month,
    COUNT(*) AS orders,
    ROUND(SUM(total_revenue), 2) AS monthly_revenue
FROM fact_orders
WHERE strftime('%Y', order_date) = '2023'
GROUP BY order_month
ORDER BY order_month;

-- Q6. Regions where total quantity sold exceeds 20,000 units
--     (HAVING on SUM).
SELECT
    r.region_name,
    SUM(f.quantity_sold) AS total_units_sold
FROM fact_orders f
JOIN dim_region r ON f.region_id = r.region_id
GROUP BY r.region_name
HAVING SUM(f.quantity_sold) > 20000
ORDER BY total_units_sold DESC;


/* ----------------------------------------------------------
   SECTION 3: SUBQUERIES
   ---------------------------------------------------------- */

-- Q7. Find all orders whose total_revenue is above the overall
--     average total_revenue (scalar subquery in WHERE clause).
SELECT order_id, order_date, total_revenue
FROM fact_orders
WHERE total_revenue > (SELECT AVG(total_revenue) FROM fact_orders)
ORDER BY total_revenue DESC
LIMIT 20;

-- Q8. For every category, show orders that earned more revenue
--     than that category's own average revenue (CORRELATED
--     subquery -- the inner query re-runs per outer row).
SELECT
    f.order_id,
    c.category_name,
    f.total_revenue
FROM fact_orders f
JOIN dim_category c ON f.category_id = c.category_id
WHERE f.total_revenue > (
    SELECT AVG(f2.total_revenue)
    FROM fact_orders f2
    WHERE f2.category_id = f.category_id
)
ORDER BY c.category_name, f.total_revenue DESC
LIMIT 30;

-- Q9. List categories that have NEVER been paid for using
--     'Cash on Delivery' (subquery with NOT IN).
SELECT category_name
FROM dim_category
WHERE category_id NOT IN (
    SELECT DISTINCT f.category_id
    FROM fact_orders f
    JOIN dim_payment p ON f.payment_id = p.payment_id
    WHERE p.payment_method = 'Cash on Delivery'
);
