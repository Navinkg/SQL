/* ----------------------------------------------------------
   SECTION 4: CTEs (WITH clause)
   ---------------------------------------------------------- */

-- Q10. Use a CTE to first compute revenue per category, then
--      rank the categories by revenue in the outer query.
WITH category_revenue AS (
    SELECT
        c.category_name,
        SUM(f.total_revenue) AS revenue
    FROM fact_orders f
    JOIN dim_category c ON f.category_id = c.category_id
    GROUP BY c.category_name
)
SELECT
    category_name,
    ROUND(revenue, 2) AS revenue,
    ROUND(100.0 * revenue / (SELECT SUM(revenue) FROM category_revenue), 2) AS pct_of_total_revenue
FROM category_revenue
ORDER BY revenue DESC;

-- Q11. Two CTEs chained together: first find each region's
--      average discount, then flag regions that discount more
--      heavily than the company-wide average.
WITH region_discount AS (
    SELECT
        r.region_name,
        AVG(f.discount_percent) AS avg_discount
    FROM fact_orders f
    JOIN dim_region r ON f.region_id = r.region_id
    GROUP BY r.region_name
),
overall_avg AS (
    SELECT AVG(discount_percent) AS company_avg_discount
    FROM fact_orders
)
SELECT
    rd.region_name,
    ROUND(rd.avg_discount, 2) AS avg_discount,
    ROUND(oa.company_avg_discount, 2) AS company_avg_discount,
    CASE
        WHEN rd.avg_discount > oa.company_avg_discount THEN 'Above Average'
        ELSE 'At or Below Average'
    END AS discount_flag
FROM region_discount rd
CROSS JOIN overall_avg oa
ORDER BY avg_discount DESC;


/* ----------------------------------------------------------
   SECTION 5: CASE EXPRESSIONS
   ---------------------------------------------------------- */

-- Q12. Bucket every order into a revenue tier, then count how
--      many orders fall into each tier.
SELECT
    CASE
        WHEN total_revenue < 200       THEN 'Low ( < 200 )'
        WHEN total_revenue < 800       THEN 'Medium ( 200 - 799 )'
        WHEN total_revenue < 2000      THEN 'High ( 800 - 1999 )'
        ELSE 'Premium ( 2000+ )'
    END AS revenue_tier,
    COUNT(*) AS order_count,
    ROUND(SUM(total_revenue), 2) AS tier_revenue
FROM fact_orders
GROUP BY revenue_tier
ORDER BY tier_revenue DESC;

-- Q13. Classify each order's discount level and show the
--      average rating customers gave at each discount level.
SELECT
    CASE
        WHEN discount_percent = 0            THEN 'No Discount'
        WHEN discount_percent BETWEEN 1 AND 10  THEN 'Small Discount (1-10%)'
        WHEN discount_percent BETWEEN 11 AND 25 THEN 'Medium Discount (11-25%)'
        ELSE 'Large Discount (25%+)'
    END AS discount_bucket,
    COUNT(*) AS orders,
    ROUND(AVG(rating), 2) AS avg_rating
FROM fact_orders
GROUP BY discount_bucket
ORDER BY orders DESC;


/* ----------------------------------------------------------
   SECTION 6: WINDOW FUNCTIONS (intro-level)
   ---------------------------------------------------------- */

-- Q14. Rank categories by total revenue using RANK() (window
--      function replaces a manual self-join / subquery approach).
SELECT
    category_name,
    revenue,
    RANK() OVER (ORDER BY revenue DESC) AS revenue_rank
FROM (
    SELECT c.category_name, SUM(f.total_revenue) AS revenue
    FROM fact_orders f
    JOIN dim_category c ON f.category_id = c.category_id
    GROUP BY c.category_name
) AS cat_totals;

-- Q15. Running total of daily revenue across January 2023
--      (window function with ORDER BY, no PARTITION BY).
SELECT
    order_date,
    ROUND(SUM(total_revenue), 2) AS daily_revenue,
    ROUND(SUM(SUM(total_revenue)) OVER (ORDER BY order_date), 2) AS running_total_revenue
FROM fact_orders
WHERE order_date BETWEEN '2023-01-01' AND '2023-01-31'
GROUP BY order_date
ORDER BY order_date;

-- Q16. For each category, number the orders from most to least
--      recent using ROW_NUMBER() PARTITION BY, then keep only
--      each category's 3 most recent orders.
SELECT category_name, order_id, order_date, total_revenue
FROM (
    SELECT
        c.category_name,
        f.order_id,
        f.order_date,
        f.total_revenue,
        ROW_NUMBER() OVER (
            PARTITION BY c.category_name
            ORDER BY f.order_date DESC
        ) AS rn
    FROM fact_orders f
    JOIN dim_category c ON f.category_id = c.category_id
) ranked
WHERE rn <= 3
ORDER BY category_name, order_date DESC;


/* ----------------------------------------------------------
   SECTION 7: UNION / SET OPERATIONS
   ---------------------------------------------------------- */

-- Q17. Combine a list of "top revenue" categories and "top
--      rated" categories into a single watch-list, removing
--      duplicates (UNION).
SELECT category_name, 'Top Revenue' AS reason
FROM (
    SELECT c.category_name, SUM(f.total_revenue) AS revenue
    FROM fact_orders f JOIN dim_category c ON f.category_id = c.category_id
    GROUP BY c.category_name
    ORDER BY revenue DESC
    LIMIT 3
)
UNION
SELECT category_name, 'Top Rated' AS reason
FROM (
    SELECT c.category_name, AVG(f.rating) AS avg_rating
    FROM fact_orders f JOIN dim_category c ON f.category_id = c.category_id
    GROUP BY c.category_name
    ORDER BY avg_rating DESC
    LIMIT 3
);


